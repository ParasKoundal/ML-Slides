// Build step: pre-render every TeX string to SVG (no maths library at runtime),
// then bundle the deck into one self-contained HTML file.
//   node tools/build.mjs
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
import { mathjax } from 'mathjax-full/js/mathjax.js';
import { TeX } from 'mathjax-full/js/input/tex.js';
import { SVG } from 'mathjax-full/js/output/svg.js';
import { liteAdaptor } from 'mathjax-full/js/adaptors/liteAdaptor.js';
import { RegisterHTMLHandler } from 'mathjax-full/js/handlers/html.js';
import { AllPackages } from 'mathjax-full/js/input/tex/AllPackages.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const js = f => path.join(ROOT, 'js', f);
const files = fs.readdirSync(path.join(ROOT, 'js')).filter(f => /^(ch|x)\d\.js$|^core\.js$/.test(f));
const texs = new Set();
for (const f of files) for (const m of fs.readFileSync(js(f), 'utf8').matchAll(/M\(T`([^`]*)`\)/g)) texs.add(m[1]);

const adaptor = liteAdaptor(); RegisterHTMLHandler(adaptor);
const doc = mathjax.document('', { InputJax: new TeX({ packages: AllPackages }), OutputJax: new SVG({ fontCache: 'none' }) });
const out = {}; let bad = 0;
for (const t of texs) {
  try {
    const node = doc.convert(t, { display: false, em: 16, ex: 8, containerWidth: 1600 });
    let svg = adaptor.innerHTML(node);
    if (/merror|data-mjx-error/.test(svg)) { console.error('TeX error:', t); bad++; }
    out[t] = svg;
  } catch (e) { console.error('TeX failed:', t, e.message); bad++; }
}
fs.writeFileSync(js('math.js'), '/* generated by tools/build.mjs: TeX -> SVG */\nwindow.MATH = ' + JSON.stringify(out) + ';\n');
console.log(`maths: ${texs.size} expressions, ${bad} errors`);

// bundle
let html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
html = html.replace(/<link rel="stylesheet" href="css\/deck.css">/, () => `<style>\n${fs.readFileSync(path.join(ROOT, 'css/deck.css'), 'utf8')}\n</style>`);
html = html.replace(/<script src="(js\/[^"]+)"><\/script>/g, (_, f) => `<script>\n${fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/<\/script/g, '<\\/script')}\n</script>`);
fs.mkdirSync(path.join(ROOT, 'dist'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'dist/Lecture 2 - Learning by gradients (2-hour edition).html'), html);
// the hosted page gets its own document skeleton, so strip ours
const art = html.replace(/<!doctype html>\s*<html[^>]*>\s*<head>\s*<meta charset="utf-8">\s*<meta name="viewport"[^>]*>/i, '')
  .replace(/<\/head>\s*<body>/i, '').replace(/<\/body>\s*<\/html>\s*$/i, '')
  .replace('<title>Learning by Gradients</title>', '<title>Learning by Gradients</title>\n<meta name="claude:viewport-fit-sides" content="cover">');
fs.writeFileSync(path.join(ROOT, 'dist/artifact.html'), art);
console.log('bundled', (html.length / 1e6).toFixed(2), 'MB');
